import { chromium } from 'playwright-core';
const out = '/workspace/truco-da-quebrada/';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream', '--no-sandbox'] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, permissions: ['microphone'] });
const p = await ctx.newPage();
p.on('pageerror', (e) => console.log('PAGEERR', e.message));
await p.goto('http://localhost:4173/?screen=table&n=4&demo=truco'); await p.waitForTimeout(650);
await p.screenshot({ path: out + 'docs-truco-moment-mobile.png' });
await p.waitForTimeout(1500); await p.screenshot({ path: out + 'docs-truco-respond-mobile.png' });
await p.getByRole('button', { name: 'CORRE' }).click(); await p.waitForTimeout(350);
await p.screenshot({ path: out + 'docs-correu-mobile.png' });
await p.goto('http://localhost:4173/?screen=table&n=4'); await p.waitForTimeout(400);
const btn = p.getByLabel('Segure para gravar áudio de zoeira'); await btn.scrollIntoViewIfNeeded();
const box = await btn.boundingBox();
await p.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await p.mouse.down(); await p.waitForTimeout(2200);
await p.screenshot({ path: out + 'docs-clip-recording-mobile.png', fullPage: true });
await p.mouse.up(); await p.waitForTimeout(800);
await p.screenshot({ path: out + 'docs-clip-preview-mobile.png', fullPage: true });
console.log(await p.locator('.clip').innerText());
await b.close();
